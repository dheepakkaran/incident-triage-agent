"""Shared eval helpers: labels/splits (only eval code may read labels), scoring, result files.

Every number in the README comes from the JSON files this module writes, and from
eval/results/RESULTS.md, which `write_results_table()` rebuilds from those JSON files.
"""

import json
import re
import time
from datetime import date
from pathlib import Path

from triage.config import ROOT, get_settings

RESULTS_DIR = ROOT / "eval" / "results"


def load_labels() -> dict:
    return json.loads(get_settings().labels_path.read_text())


def load_split(split: str) -> list[str]:
    return json.loads(get_settings().splits_path.read_text())[split]


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9.]+", "-", text.lower()).strip("-")


def result_path(kind: str, model: str, split: str, variant: str = "") -> Path:
    name = "_".join(p for p in (date.today().isoformat(), slug(model), split, variant, kind) if p)
    return RESULTS_DIR / f"{name}.json"


def save(path: Path, payload: dict) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, default=str) + "\n")
    write_results_table()
    return path


def mean(values: list[float]) -> float:
    return round(sum(values) / len(values), 3) if values else 0.0


def rate(flags: list[bool]) -> float:
    return round(sum(flags) / len(flags), 3) if flags else 0.0


def now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


# ---- the markdown table the README copies ---------------------------------


def _pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def write_results_table() -> Path:
    """Rebuild eval/results/RESULTS.md from every result JSON in the folder."""
    files = sorted(RESULTS_DIR.glob("*.json"))
    agent, baseline, adversarial = [], [], []
    for f in files:
        data = json.loads(f.read_text())
        kind = data.get("kind")
        if kind == "agent":
            agent.append((f.name, data))
        elif kind == "baseline":
            baseline.append((f.name, data))
        elif kind == "adversarial":
            adversarial.append((f.name, data))

    lines = ["# Eval results", "", "Generated by `eval/common.py` from the JSON files in this folder. Do not edit by hand.", ""]
    if agent or baseline:
        lines += [
            "## Root-cause accuracy",
            "",
            "| run | split | n | top-1 | top-3 | fault type | runbook hit | escalated | wrong & confident | wrong & proposed | tool calls | tokens | LLM latency (s) | file |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for name, d in agent:
            m = d["metrics"]
            label = f"agent {d['model']} prompt {d['prompt_version']}, reviewer {'on' if d['reviewer_enabled'] else 'off'}"
            # wrong & proposed: top-1 wrong AND not escalated, i.e. a wrong fix reached the approval step.
            proposed_wrong = sum(1 for c in d["cases"] if not c["top1"] and not c["escalated"])
            lines.append(
                f"| {label} | {d['split']} | {m['n']} | {_pct(m['top1'])} | {_pct(m['top3'])} | {_pct(m['fault_type'])} | "
                f"{_pct(m['runbook_hit'])} | {_pct(m['escalation_rate'])} | {m['wrong_but_confident']} | {proposed_wrong} | "
                f"{m['avg_tool_calls']} | {m['avg_tokens']:.0f} | {m['avg_llm_latency_s']} | `{name}` |"
            )
        for name, d in baseline:
            m = d["metrics"]
            lines.append(
                f"| baseline: {d['method']} | {d['split']} | {m['n']} | {_pct(m['top1'])} | {_pct(m['top3'])} | "
                f"{_pct(m['fault_type'])} | - | - | - | - | 0 | 0 | 0 | `{name}` |"
            )
        lines.append("")
    for name, d in adversarial:
        lines += [f"## Adversarial guardrail suite: {d['blocked']} / {d['total']} blocked", "", f"Source: `{name}`", ""]
        lines += ["| # | scenario | model | result | detail |", "|---|---|---|---|---|"]
        for s in d["scenarios"]:
            lines.append(f"| {s['id']} | {s['name']} | {s['model']} | {'blocked' if s['blocked'] else 'NOT blocked'} | {s['detail']} |")
        lines.append("")
    out = RESULTS_DIR / "RESULTS.md"
    out.write_text("\n".join(lines))
    return out
